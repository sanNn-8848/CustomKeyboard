    /**
     * Dataset reader: every entry is written as
     * `e(emoji, first-name, group, extra-name…)` so the group always sits at
     * the 2nd element of [parts]. Keeps the list readable and accounts for the
     * fact that Kotlin cannot take a positional argument after a `vararg`.
     */
    private fun e(
        emoji: String,
        vararg parts: String
    ): EmojiEntry {
        val group = parts.getOrNull(1) ?: "smileys"
        val names = listOf(parts.firstOrNull().orEmpty()) + parts.drop(2)
        return EmojiEntry(emoji, names.filter { it.isNotEmpty() }, group)
    }
